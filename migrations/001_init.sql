-- Users are mirrored from the JWT on first connect (auth stays the source of truth).
create table chat_users (
  id           text primary key,
  name         text not null,
  email        text not null,
  role         text not null default 'user',
  created_at   timestamptz not null default now(),
  last_seen_at timestamptz not null default now()
);
create index chat_users_name_idx  on chat_users (lower(name) text_pattern_ops);
create index chat_users_email_idx on chat_users (lower(email));

-- One row per 1:1 conversation. dm_key = the two user ids sorted and joined, so a pair can only have one DM.
-- last_seq is a per-conversation counter: every message gets the next number, which gives gap-free ordering
-- and lets a client say "give me everything after seq N" when it reconnects.
create table conversations (
  id              uuid primary key default gen_random_uuid(),
  dm_key          text not null unique,
  last_seq        bigint not null default 0,
  last_message_at timestamptz,
  created_at      timestamptz not null default now()
);

create table conversation_members (
  conversation_id uuid   not null references conversations(id) on delete cascade,
  user_id         text   not null references chat_users(id) on delete cascade,
  last_read_seq   bigint not null default 0,
  primary key (conversation_id, user_id)
);
create index conversation_members_user_idx on conversation_members (user_id);

create table messages (
  id              uuid primary key default gen_random_uuid(),
  conversation_id uuid   not null references conversations(id) on delete cascade,
  seq             bigint not null,
  sender_id       text   not null references chat_users(id),
  client_id       uuid   not null,          -- generated by the sender; makes retries idempotent
  body            text   not null check (char_length(body) between 1 and 1000),
  created_at      timestamptz not null default now(),
  deleted_at      timestamptz,
  unique (conversation_id, seq),
  unique (sender_id, client_id)
);
create index messages_created_idx on messages (created_at desc);
